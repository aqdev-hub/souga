// صيغة الجمع لأسماء الخصائص الاختيارية في عبارات مثل "هل جميع الألوان لها نفس السعر؟".
// خريطة للأسماء الشائعة؛ ما لا تعرفه يبقى باسمه كما أدخله البائع (آمن لغوياً).

const Map<String, String> _plurals = {
  'اللون': 'الألوان', 'لون': 'الألوان', 'الالوان': 'الألوان',
  'المقاس': 'المقاسات', 'مقاس': 'المقاسات',
  'الحجم': 'الأحجام', 'حجم': 'الأحجام',
  'السعة': 'السعات', 'سعة': 'السعات',
  'الوزن': 'الأوزان', 'وزن': 'الأوزان',
  'الطول': 'الأطوال', 'طول': 'الأطوال',
  'العرض': 'الأعراض', 'الارتفاع': 'الارتفاعات',
  'القياس': 'القياسات', 'قياس': 'القياسات',
  'النوع': 'الأنواع', 'نوع': 'الأنواع',
  'الشكل': 'الأشكال', 'التصميم': 'التصاميم',
  'النكهة': 'النكهات', 'نكهة': 'النكهات', 'الطعم': 'الأطعمة',
  'العبوة': 'العبوات', 'الموديل': 'الموديلات', 'الإصدار': 'الإصدارات',
  'الخامة': 'الخامات', 'القماش': 'الأقمشة', 'نوع القماش': 'أنواع القماش',
  'التخزين': 'سعات التخزين', 'الرام': 'سعات الرام', 'الذاكرة': 'سعات الذاكرة',
  'المعالج': 'المعالجات', 'الباقة': 'الباقات', 'الفئة': 'الفئات',
};

String pluralizeAttrName(String name) {
  final n = name.trim();
  return _plurals[n] ?? n;
}

/// "الألوان" / "الألوان والمقاسات" / "الألوان والمقاسات والأحجام".
String joinAttrNames(Iterable<String> names) {
  final list = [for (final n in names) pluralizeAttrName(n)];
  if (list.isEmpty) return 'الخيارات';
  final b = StringBuffer(list.first);
  for (var i = 1; i < list.length; i++) {
    b.write(' و${list[i]}');
  }
  return b.toString();
}
